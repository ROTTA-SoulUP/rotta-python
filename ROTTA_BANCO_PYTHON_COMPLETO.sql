-- ROTTA: banco completo para a versao Python entregue junto deste arquivo.
-- Oracle 12c+. Execute com F5 no SQL Developer, na sua conexao FIAP.
-- Nao execute junto do antigo script de tres tabelas.
-- Se encontrar objetos existentes, para antes de criar qualquer tabela.
-- DDL confirma transacoes. O script nao apaga nem substitui objetos.
SET DEFINE OFF;
SET SERVEROUTPUT ON;
DECLARE
  existentes NUMBER;
BEGIN
  SELECT COUNT(*) INTO existentes FROM user_objects
  WHERE object_name IN ('TB_USUARIO','TB_DESAFIO','TB_CARTEIRA','TB_PARTICIPACAO','TB_COMPROVACAO','TB_VALIDACAO','TB_MOVIMENTACAO','TB_RESGATE');
  IF existentes > 0 THEN RAISE_APPLICATION_ERROR(-20001, 'Ja existem objetos com os nomes das tabelas. Nenhuma criacao iniciada.'); END IF;
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_USUARIO (
ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
NM_USUARIO VARCHAR2(100 CHAR) NOT NULL,
EMAIL VARCHAR2(150 CHAR) NOT NULL UNIQUE,
SENHA VARCHAR2(128 CHAR),
SENHA_HASH VARCHAR2(255 CHAR),
DT_CADASTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CHECK (TRIM(NM_USUARIO) IS NOT NULL),
CHECK (TRIM(EMAIL) IS NOT NULL AND EMAIL = LOWER(TRIM(EMAIL)))
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_DESAFIO (
ID_DESAFIO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
NM_DESAFIO VARCHAR2(100 CHAR) NOT NULL UNIQUE,
DS_DESCRICAO VARCHAR2(500 CHAR) NOT NULL,
PONTOS_DESAFIO NUMBER(10,0) NOT NULL CHECK (PONTOS_DESAFIO > 0),
ST_ATIVO CHAR(1) DEFAULT 'S' NOT NULL CHECK (ST_ATIVO IN ('S','N'))
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_CARTEIRA (
ID_CARTEIRA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_USUARIO NUMBER NOT NULL UNIQUE REFERENCES TB_USUARIO(ID_USUARIO),
SALDO_PONTOS NUMBER(10,0) DEFAULT 0 NOT NULL CHECK (SALDO_PONTOS >= 0),
DT_ATUALIZACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_PARTICIPACAO (
ID_PARTICIPACAO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_USUARIO NUMBER NOT NULL REFERENCES TB_USUARIO(ID_USUARIO),
ID_DESAFIO NUMBER NOT NULL REFERENCES TB_DESAFIO(ID_DESAFIO),
DT_PARTICIPACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_COMPROVACAO (
ID_COMPROVACAO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_PARTICIPACAO NUMBER NOT NULL UNIQUE REFERENCES TB_PARTICIPACAO(ID_PARTICIPACAO),
DS_DESCRICAO VARCHAR2(500 CHAR) NOT NULL,
REFERENCIA_ARQUIVO VARCHAR2(500 CHAR),
DT_ENVIO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CHECK (TRIM(DS_DESCRICAO) IS NOT NULL)
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_VALIDACAO (
ID_VALIDACAO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_COMPROVACAO NUMBER NOT NULL UNIQUE REFERENCES TB_COMPROVACAO(ID_COMPROVACAO),
ST_RESULTADO VARCHAR2(10 CHAR) NOT NULL CHECK (ST_RESULTADO IN ('APROVADO','REJEITADO')),
METODO VARCHAR2(10 CHAR) DEFAULT 'SIMULADA' NOT NULL CHECK (METODO IN ('SIMULADA','IA','MANUAL')),
OBSERVACAO VARCHAR2(500 CHAR) NOT NULL,
DT_ANALISE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_MOVIMENTACAO (
ID_MOVIMENTACAO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_CARTEIRA NUMBER NOT NULL REFERENCES TB_CARTEIRA(ID_CARTEIRA),
ID_VALIDACAO NUMBER UNIQUE REFERENCES TB_VALIDACAO(ID_VALIDACAO),
TP_MOVIMENTACAO VARCHAR2(10 CHAR) NOT NULL CHECK (TP_MOVIMENTACAO IN ('CREDITO','RESGATE')),
VALOR NUMBER(10,0) NOT NULL,
DS_DESCRICAO VARCHAR2(300 CHAR) NOT NULL,
DT_MOVIMENTACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CHECK ((TP_MOVIMENTACAO='CREDITO' AND VALOR>0 AND ID_VALIDACAO IS NOT NULL)
 OR (TP_MOVIMENTACAO='RESGATE' AND VALOR<0 AND ID_VALIDACAO IS NULL))
)]';
  EXECUTE IMMEDIATE q'[CREATE TABLE TB_RESGATE (
ID_RESGATE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
ID_MOVIMENTACAO NUMBER NOT NULL UNIQUE REFERENCES TB_MOVIMENTACAO(ID_MOVIMENTACAO),
TP_BENEFICIO VARCHAR2(10 CHAR) NOT NULL CHECK (TP_BENEFICIO IN ('PASSAGEM','QRCODE','CARTAO')),
PONTOS_UTILIZADOS NUMBER(10,0) NOT NULL CHECK (PONTOS_UTILIZADOS > 0),
CODIGO VARCHAR2(40 CHAR) NOT NULL UNIQUE,
ST_STATUS VARCHAR2(10 CHAR) DEFAULT 'SIMULADO' NOT NULL CHECK (ST_STATUS='SIMULADO'),
DT_RESGATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)]';
  DBMS_OUTPUT.PUT_LINE('ESTRUTURA CRIADA: 8 tabelas.');
-- Carga inicial de desafios, sem usuarios ou senhas.
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Separar reciclaveis' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Separar materiais para reciclagem.',15)]';
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Usar garrafa reutilizavel' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Substituir garrafas descartaveis por uma reutilizavel.',20)]';
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Caminhar ou pedalar' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Realizar um trajeto a pe ou de bicicleta.',40)]';
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Usar sacola reutilizavel' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Evitar sacolas descartaveis.',25)]';
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Economizar energia' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Registrar uma acao para reduzir o consumo de energia.',30)]';
  EXECUTE IMMEDIATE q'[MERGE INTO TB_DESAFIO d USING (SELECT 'Evitar descarte incorreto' nome FROM dual) s ON (d.NM_DESAFIO=s.nome) WHEN NOT MATCHED THEN INSERT (NM_DESAFIO,DS_DESCRICAO,PONTOS_DESAFIO) VALUES (s.nome,'Destinar residuos ao local adequado.',20)]';
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('DESAFIOS CARREGADOS: confira a consulta final.');
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/
SELECT table_name FROM user_tables WHERE table_name IN ('TB_USUARIO','TB_DESAFIO','TB_CARTEIRA','TB_PARTICIPACAO','TB_COMPROVACAO','TB_VALIDACAO','TB_MOVIMENTACAO','TB_RESGATE') ORDER BY table_name;
